"""Regenerate the checked-in LVGL 8 Barlow fonts (requires Pillow 13.0.0)."""
from pathlib import Path
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'firmware/components/board_display/fonts'


def generate(size, bold=False):
    face = OUT / ('BarlowSemiCondensed-Bold.ttf' if bold else 'BarlowSemiCondensed-Medium.ttf')
    font = ImageFont.truetype(str(face), size)
    ascent, descent = font.getmetrics()
    name = f'rnbo_barlow_{size}'
    bitmap, glyphs = [], [(0, 0, 0, 0, 0, 0)]
    for code in range(32, 127):
        char = chr(code)
        x0, y0, x1, y1 = font.getbbox(char, anchor='ls')
        width, height = x1-x0, y1-y0
        im = Image.new('L', (max(1, width), max(1, height)))
        ImageDraw.Draw(im).text((-x0, -y0), char, font=font, fill=255, anchor='ls')
        pixels = [int(value >= 128) for value in im.get_flattened_data()] if width*height else []
        packed = []
        for start in range(0, len(pixels), 8):
            packed.append(sum(bit << (7-i) for i, bit in enumerate(pixels[start:start+8])))
        glyphs.append((len(bitmap), round(font.getlength(char)*16), width, height, x0, -y1))
        bitmap.extend(packed)
    lines = ['/* Generated by host/visual/fonts.py; Barlow font data: SIL OFL 1.1. */',
             '#include "lvgl.h"', 'static const uint8_t bitmap[] = {']
    lines += ['    '+','.join(str(v) for v in bitmap[i:i+24])+',' for i in range(0,len(bitmap),24)]
    lines += ['};', 'static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {']
    for index, advance, width, height, x, y in glyphs:
        lines.append(f'    {{.bitmap_index={index},.adv_w={advance},.box_w={width},.box_h={height},.ofs_x={x},.ofs_y={y}}},')
    lines += ['};', 'static const lv_font_fmt_txt_cmap_t maps[] = {',
              '    {.range_start=32,.range_length=95,.glyph_id_start=1,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}',
              '};', 'static lv_font_fmt_txt_glyph_cache_t cache;',
              'static const lv_font_fmt_txt_dsc_t descriptor = {',
              '    .glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=maps,.cmap_num=1,.bpp=1,.cache=&cache',
              '};', f'const lv_font_t {name} = {{',
              '    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
              f'    .line_height={ascent+descent},.base_line={descent},.dsc=&descriptor', '};', '']
    (OUT / (name+'.c')).write_text('\n'.join(lines))
    if size==12:
        (ROOT/'host/visual/graph_font_metrics.json').write_text(json.dumps(
            {chr(i+31):g[1] for i,g in enumerate(glyphs) if i},sort_keys=True,indent=2)+'\n')


if __name__ == '__main__':
    for pixels, bold in ((12,False),(14,False),(16,False),(22,True)):
        generate(pixels,bold)
