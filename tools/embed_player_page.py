#!/usr/bin/env python3
"""Deterministically embed the self-contained page as gzip flash data."""
from pathlib import Path
import gzip
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'firmware/components/player_remote/web/index.html'
target=source.parents[1]/'player_remote_page.h'
data=gzip.compress(source.read_bytes(),compresslevel=9,mtime=0)
text='/* Generated by tools/embed_player_page.py; gzip, served directly from flash. */\n#pragma once\nstatic const unsigned char player_remote_page[] = {\n'
text+='\n'.join('    '+','.join(str(x) for x in data[i:i+24])+',' for i in range(0,len(data),24))+'\n};\n'
target.write_text(text)
print(f'{len(source.read_bytes())} bytes HTML -> {len(data)} bytes compressed flash')
